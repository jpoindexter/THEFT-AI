type ProjectWorkspaceDefaults = {
  executionWorkspacePolicy?: {
    defaultMode?: string | null;
    defaultProjectWorkspaceId?: string | null;
    enabled?: boolean;
  } | null;
  workspaces?: Array<{ id: string; isPrimary: boolean }>;
} | null | undefined;

export function defaultProjectWorkspaceIdForProject(project: ProjectWorkspaceDefaults) {
  if (!project) return "";
  return project.executionWorkspacePolicy?.defaultProjectWorkspaceId
    ?? project.workspaces?.find((workspace) => workspace.isPrimary)?.id
    ?? project.workspaces?.[0]?.id
    ?? "";
}

export function defaultExecutionWorkspaceModeForProject(project: ProjectWorkspaceDefaults) {
  const defaultMode = project?.executionWorkspacePolicy?.enabled
    ? project.executionWorkspacePolicy.defaultMode
    : null;
  if (
    defaultMode === "isolated_workspace" ||
    defaultMode === "operator_branch" ||
    defaultMode === "adapter_default"
  ) {
    return defaultMode === "adapter_default" ? "agent_default" : defaultMode;
  }
  return "shared_workspace";
}

export function defaultExecutionWorkspaceModeForIssueDefaults(
  defaults: {
    executionWorkspaceId?: unknown;
    executionWorkspaceMode?: unknown;
  },
  project: ProjectWorkspaceDefaults,
) {
  if (typeof defaults.executionWorkspaceId === "string" && defaults.executionWorkspaceId.length > 0) {
    return "reuse_existing";
  }
  return typeof defaults.executionWorkspaceMode === "string" && defaults.executionWorkspaceMode.length > 0
    ? defaults.executionWorkspaceMode
    : defaultExecutionWorkspaceModeForProject(project);
}

export function issueExecutionWorkspaceModeForExistingWorkspace(mode: string | null | undefined) {
  if (mode === "isolated_workspace" || mode === "operator_branch" || mode === "shared_workspace") {
    return mode;
  }
  if (mode === "adapter_managed" || mode === "cloud_sandbox") {
    return "agent_default";
  }
  return "shared_workspace";
}
